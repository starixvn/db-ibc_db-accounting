					OR cg.isautopositiontaking	<> cs.isautolivepositiontaking
					OR cg.autompositiontaking	<> cs.autolivempositiontaking
					OR cg.isautompositiontaking	<> cs.isautolivempositiontaking
					)
				AND c.custid <= @maxCustID

			IF @@ROWCOUNT <> 10000
				BREAK
			WAITFOR DELAY '00:00:01'
		END
