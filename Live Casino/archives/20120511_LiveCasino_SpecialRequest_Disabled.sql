insert into #temp (custid, isfinished)
select c.custid, 0
from custinfo c with(nolock)
where srecommend IN (select custid from @customers where roleid = 4) and custid <= @maxCustid
union all
select c.custid, 0
from custinfo c with(nolock)
where mrecommend IN (select custid from @customers where roleid = 3) and custid <= @maxCustid
union all
select c.custid, 0
from custinfo c with(nolock)
where recommend IN (select custid from @customers where roleid = 2) and custid <= @maxCustid
union all
select c.custid, 0
from custinfo c with(nolock)
