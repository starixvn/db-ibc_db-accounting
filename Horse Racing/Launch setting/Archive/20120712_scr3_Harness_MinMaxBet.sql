create table #temp (custid int primary key, isfinished bit)

insert into #temp (custid, isfinished)
SELECT distinct c.custid, 0
FROM custsetting3rd cs3 
		INNER JOIN custinfo c WITH(NOLOCK) ON cs3.custid = c.custid
		INNER JOIN @betSetting b ON c.currency = b.Currency		
WHERE c.srecommend NOT IN (SELECT custid FROM @depSuper)
	AND c.roleid <= 4
	AND cs3.sporttype = 153
	AND cs3.bettype BETWEEN 51 AND 52
	AND (cs3.minbet <> b.minbet OR cs3.maxbet <> b.maxbet)


