


ALTER PROCEDURE [Acc_ExecRep_09]	
(
	@srecommend INT,
	@minbet MONEY,
	@maxbet MONEY,
	@maxpermatch MONEY
)
AS
BEGIN

	IF (SELECT COUNT('') FROM sys.objects WHERE name IN ('custinfo','custsetting3rd') AND type = 'U') = 2
	BEGIN
		WHILE 1 = 1 
		BEGIN
			UPDATE TOP(20000) cs3 WITH(ROWLOCK,UPDLOCK)
			SET cs3.minbet = @minbet,
				cs3.maxbet = @maxbet
			FROM custsetting3rd cs3 
				INNER JOIN custinfo c WITH(NOLOCK) ON cs3.custid = c.custid
			WHERE c.srecommend = @srecommend AND roleid <= 4
				AND cs3.sporttype = 152 AND cs3.bettype BETWEEN 41 AND 42
				AND (cs3.minbet <> @minbet OR cs3.maxbet <> @maxbet)
			IF @@ROWCOUNT <> 20000
				BREAK		
		END
	END

	IF EXISTS (SELECT 1 FROM sys.objects WHERE name IN ('custinfo') AND type = 'U')
	BEGIN
		WHILE 1 = 1
		BEGIN
			UPDATE TOP (20000) custinfo WITH(ROWLOCK,UPDLOCK)
			SET maxpermatch152_uk = @maxpermatch
			WHERE srecommend = @srecommend   AND roleid <= 4
				AND maxpermatch152_uk <> @maxpermatch

			IF @@ROWCOUNT <> 20000
				BREAK
		END
	END

END


