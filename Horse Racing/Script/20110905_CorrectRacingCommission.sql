DECLARE @masterID INT,
		@i INT
SELECT @i = 1

SELECT @masterID = custid
	FROM @tmp
	WHERE id = @i

WHILE @i <= 123
BEGIN
	-- update master
	UPDATE custsetting3rd WITH(ROWLOCK,UPDLOCK)
	SET adiscount = 0.01
	WHERE custid = @masterID AND sporttype BETWEEN 151 AND 153 AND bettype BETWEEN 41 and 52

	--update member
	UPDATE cs3 WITH(ROWLOCK,UPDLOCK)
	SET sdiscount = 0.01,
		adiscount = 0.01
	FROM custsetting3rd cs3 
		INNER JOIN custinfo c WITH(NOLOCK) ON cs3.custid = c.custid
	WHERE c.mrecommend = @masterID AND roleid = 1 AND sporttype BETWEEN 151 AND 153 AND bettype BETWEEN 41 and 52
	
	SET @i = @i + 1

	SELECT @masterID = custid 
	FROM @tmp
	WHERE id = @i
	
	WAITFOR DELAY '00:00:02'
END



