CREATE view [dbo].[partitionDetail]
as
select 
	ds.name,   
	p.object_id,   
   p.partition_number,
   p.rows,
   index_name = i.name,
   index_type_desc = i.type_desc,
    prv.value,
	ds2.name file_group
from 
   sys.partitions p
inner join
   sys.indexes i on p.object_id = i.object_id and p.index_id = i.index_id
