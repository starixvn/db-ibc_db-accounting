CREATE PROCEDURE [dbo].[CheckAccountError]
AS

create table #match (matchid int)
insert into #match
select matchid from match (nolock) where eventdate = '6 nov 2005'

create table #bet (refno bigint, matchid int, custid int, odds money,
winlost money, awinlost money, mwinlost money,
stake money)
insert into #bet select refno, matchid, custid, odds, winlost, awinlost, mwinlost, stake from bettrans
where winlostdate = '6 nov 2005'

select b.matchid,sum((awinlost + mwinlost) * e.actualrate) from #bet b (nolock)
LEFT OUTER join #match m on b.matchid = m.matchid
inner join customer c (nolock) on b.custid = c.custid
inner join exchange e (nolock) on c.currency = e.exchangeid
where c.custid <> 0 
group by b.matchid
order by b.matchid

select b.matchid, sum((creditamt-debitamt) * e.actualrate) from custaccount ca (nolock)
inner join #bet b on ca.transcode = b.refno
inner join customer c (nolock) on ca.custid = c.custid
inner join exchange e (nolock) on c.currency = e.exchangeid
where transtype IN ('POS')
group by b.matchid
order by b.matchid
